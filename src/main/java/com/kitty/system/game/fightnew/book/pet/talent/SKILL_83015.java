    @Override
    public NutMap passive(final Fight fight, final FightObject effector, final Object... args) {
        final SkillRecord skillRecord = FightParamPool.addSkillRecord(fight, 7, effector.getId(), 83015);
        final double percent = 0.6;
        final int oldMana = effector.getCurrMana();
        final int mana = (int)Double.parseDouble(BigDecimalUtil.multiply(String.valueOf(effector.getMaxMana()), String.valueOf(percent)));
        final int newMana = Math.min(effector.getMaxMana(), oldMana + mana);
        if (newMana - oldMana > 0) {
            ActionParamUtils.changeMana(fight, effector, effector, 7, 83015, 2, newMana - oldMana);
            skillRecord.setT(effector.getId());
        }
        return null;
    }
    
