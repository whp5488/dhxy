public class SKILL_80012 extends SkillProcessor
{
    public SKILL_80012() {
    }
    
    @Override
    public NutMap addition(Addition addition, Object... args) {
        return null;
    }
    
    @Override
    public NutMap passive(Fight fight, FightObject effector, Object... args) {
        SkillRecord skillRecord = FightParamPool.addSkillRecord(fight, 7, (long)(int)effector.getId(), 80012);
        double percent = BigDecimalUtil.decimalScaleObjectDown(Integer.valueOf(3), Double.valueOf((0.1 + 2.0 * ((double)effector.getRelive() * 0.4 + 1.0) * PetSkillEffectorUtil.getSuffix(Integer.valueOf(effector.getLevel()), Integer.valueOf(effector.getRelive()), effector.getClose())) / 100.0));
        boolean flag = SkillAi.canAffectOnPro(percent);
        if (flag) {
            double probability = BigDecimalUtil.decimalScaleObjectDown(Integer.valueOf(3), Double.valueOf((double)effector.getCurrLife() / (double)effector.getMaxLife()));
            if (probability >= 0.3) {
                return null;
            }
            int addLife = (int)((double)effector.getMaxLife() * 0.5);
            int life = Math.min(effector.getCurrLife() + BigDecimalUtil.decimalScaleIntegerDown(Integer.valueOf(0), Integer.valueOf(addLife)), effector.getMaxLife());
            addLife = life - effector.getCurrLife();
            ActionParamUtils.changeLife(fight, effector, effector, 7, 80012, 2, addLife, false);
            skillRecord.setT((long)(int)effector.getId());
        }
        return null;
    }
    
    @Override
    public int targetCount(Fight fight, FightObject effector, Object... args) {
        return 1;
    }
    
    @Override
    public Effect effect(Fight fight, FightObject effector, FightObject target, Object... args) {
        return null;
    }
    
    @Override
    public int costMana(RoleSkill skill, Object... args) {
        return 0;
    }
}
